X_raw, y_all, DATA_NAME = load_data()
print("Dataset:", DATA_NAME, "| shape:", X_raw.shape, "| positive rate:", round(y_all.mean(), 3))

def dirichlet_partition(y, K, alpha, rng, min_size=15):
    """Split indices across K hospitals. Small alpha = very different label mixes (non-IID)."""
    while True:
        idx = [[] for _ in range(K)]
        for c in np.unique(y):
            ids = np.where(y == c)[0]
            rng.shuffle(ids)
            p = rng.dirichlet([alpha] * K)
            cuts = (np.cumsum(p) * len(ids)).astype(int)[:-1]
            for k, part in enumerate(np.split(ids, cuts)):
                idx[k] += part.tolist()
        if min(len(i) for i in idx) >= min_size:
            return [np.array(i) for i in idx]

def prepare(seed, K=5, alpha=0.5):
    rng = np.random.default_rng(seed)
    Xtr, Xte, ytr, yte = train_test_split(X_raw, y_all, test_size=0.25,
                                          stratify=y_all, random_state=seed)
    imp = SimpleImputer(strategy="median").fit(Xtr)
    sc = StandardScaler().fit(imp.transform(Xtr))   # NOTE: real FL would use federated statistics
    f = lambda A: np.hstack([sc.transform(imp.transform(A)), np.ones((len(A), 1))])  # + bias column
    Xtr_b, Xte_b = f(Xtr), f(Xte)
    parts = dirichlet_partition(ytr, K, alpha, rng)
    clients = [(Xtr_b[p], ytr[p]) for p in parts]
    return clients, Xtr_b, ytr, Xte_b, yte

clients, Xtr_b, ytr, Xte_b, yte = prepare(seed=0)
print(pd.DataFrame({
    "Hospital": [f"H{i+1}" for i in range(len(clients))],
    "Patients": [len(c[1]) for c in clients],
    "Disease rate": [round(c[1].mean(), 2) for c in clients]}).to_string(index=False))

"""## Part 2: Model and federated training (FedAvg)

A logistic regression (written in NumPy so you can see every step). In each round:
1. The server sends the global weights to every hospital.
2. Each hospital trains locally and sends back **only the weight change**.
3. The server averages the changes. **Raw patient data never leaves a hospital.**
"""

def sigmoid(z): return 1 / (1 + np.exp(-np.clip(z, -30, 30)))
def predict_proba(w, Xb): return sigmoid(Xb @ w)

def loss_each(w, Xb, y):
    p = np.clip(predict_proba(w, Xb), 1e-7, 1 - 1e-7)
    return -(y * np.log(p) + (1 - y) * np.log(1 - p))

def local_train(w, Xb, y, epochs, lr, batch, l2, rng):
    w = w.copy(); n = len(y)
    for _ in range(epochs):
        order = rng.permutation(n)
        for s in range(0, n, batch):
            b = order[s:s + batch]
            grad = Xb[b].T @ (predict_proba(w, Xb[b]) - y[b]) / len(b) + l2 * w
            w -= lr * grad
    return w

def federated_train(clients, Xte_b, yte, rounds=30, local_epochs=3, lr=0.1, batch=16,
                    l2=1e-3, clip=None, noise_mult=0.0, seed=0):
    """FedAvg. If clip is set: each hospital's update is clipped to norm <= clip, updates are
    averaged with equal weights, and Gaussian noise is added to the aggregate (central DP)."""
    rng = np.random.default_rng(seed)
    w = np.zeros(Xte_b.shape[1]); hist = []
    K = len(clients); sizes = np.array([len(c[1]) for c in clients], float)
    for _ in range(rounds):
        deltas = []
        for Xc, yc in clients:
            d = local_train(w, Xc, yc, local_epochs, lr, batch, l2, rng) - w
            if clip is not None:
                d = d * min(1.0, clip / (np.linalg.norm(d) + 1e-12))
            deltas.append(d)
        weights = np.ones(K) / K if clip is not None else sizes / sizes.sum()
        agg = (weights[:, None] * np.array(deltas)).sum(0)
        if clip is not None and noise_mult > 0:
            agg = agg + rng.normal(0, noise_mult * clip / K, size=agg.shape)
        w = w + agg
        hist.append(roc_auc_score(yte, predict_proba(w, Xte_b)))
    return w, hist

# quick demo on seed 0
w_fed, hist_fed = federated_train(clients, Xte_b, yte)
print("FedAvg test AUC after 30 rounds:", round(hist_fed[-1], 3))

"""## Part 3: Differential privacy (DP)

Even model updates can leak information about individual patients. DP limits this:
- **Clip** each hospital's update to a maximum norm `C` (bounds any one hospital's influence).
- **Add Gaussian noise** scaled by `noise_mult x C` to the aggregate.

More noise means stronger privacy but lower accuracy. The next cell shows that trade-off.

*Note:* this notebook reports the **noise multiplier**, not a formal epsilon. For a formal (epsilon, delta) guarantee, use a privacy accountant such as Opacus or TensorFlow Privacy.
"""

noise_levels = [0.0, 0.5, 1.0, 2.0, 4.0]
plt.figure(figsize=(8, 4.5))
plt.plot(hist_fed, label="FedAvg (no DP)", linewidth=2)
for s in noise_levels[1:]:
    _, h = federated_train(clients, Xte_b, yte, clip=1.0, noise_mult=s, seed=1)
    plt.plot(h, label=f"DP-FedAvg (noise={s})")
plt.xlabel("Communication round"); plt.ylabel("Test AUC")
plt.title("Convergence under different privacy levels")
plt.legend(); plt.grid(alpha=0.3); plt.tight_layout()
plt.savefig("convergence.png", dpi=150); plt.show()

"""## Part 4: Secure aggregation (demo)

With plain FL the server sees each hospital's update individually. **Secure aggregation** adds random masks that cancel when summed, so the server learns **only the total**.

This is a simplified demonstration (pairwise additive masks). Real protocols also handle key agreement and hospitals dropping out.
"""

def one_round_deltas(clients, w, seed=0):
    rng = np.random.default_rng(seed)
    return [local_train(w, Xc, yc, 3, 0.1, 16, 1e-3, rng) - w for Xc, yc in clients]

def mask_updates(deltas, rng, scale=5.0):
    masked = [d.copy() for d in deltas]
    for i in range(len(deltas)):
        for j in range(i + 1, len(deltas)):
            m = rng.normal(0, scale, size=deltas[0].shape)   # shared secret between i and j
            masked[i] += m      # hospital i adds the mask
            masked[j] -= m      # hospital j subtracts the same mask
    return masked

deltas = one_round_deltas(clients, np.zeros(Xte_b.shape[1]))
masked = mask_updates(deltas, np.random.default_rng(7))

print("Hospital 1 raw update    :", np.round(deltas[0][:5], 3))
print("Hospital 1 masked update :", np.round(masked[0][:5], 3), "<- what the server sees")
print("\nSum of raw updates      :", np.round(np.sum(deltas, axis=0)[:5], 3))
print("Sum of masked updates   :", np.round(np.sum(masked, axis=0)[:5], 3))
print("\nAggregate identical?", np.allclose(np.sum(deltas, axis=0), np.sum(masked, axis=0)))
print("Correlation raw vs masked (hospital 1):",
      round(float(np.corrcoef(deltas[0], masked[0])[0, 1]), 3), "(near 0 = masked update reveals little)")

"""## Part 5: Measuring privacy leakage (membership inference)

A **membership inference attack** asks: *given a patient record, was it used to train this model?* Models often have lower loss on training patients than on unseen ones. We run a simple loss-threshold attack as a **privacy audit**:

- Attack AUC **0.5** = the attacker cannot tell (good privacy)
- Attack AUC **well above 0.5** = the model leaks membership
"""

def mia_auc(w, Xm, ym, Xn, yn):
    """Loss-based membership inference. Members = training data, non-members = test data."""
    lm, ln = loss_each(w, Xm, ym), loss_each(w, Xn, yn)
    scores = np.r_[-lm, -ln]
    labels = np.r_[np.ones(len(lm)), np.zeros(len(ln))]
    return roc_auc_score(labels, scores)

def run_experiment(seed, K=5, alpha=0.5, clip=1.0, noise_levels=(0.5, 1.0, 2.0, 4.0)):
    clients, Xtr_b, ytr, Xte_b, yte = prepare(seed, K, alpha)
    rows = []
    def add(name, w):
        rows.append({"Seed": seed, "Model": name,
                     "Test AUC": roc_auc_score(yte, predict_proba(w, Xte_b)),
                     "Attack AUC": mia_auc(w, Xtr_b, ytr, Xte_b, yte)})
    rng = np.random.default_rng(seed)
    # Local-only: each hospital trains alone
    for i, (Xc, yc) in enumerate(clients):
        w = local_train(np.zeros(Xte_b.shape[1]), Xc, yc, 100, 0.1, 16, 1e-3, rng)
        add(f"Local-only (avg of hospitals)", w)
    # Centralized (pooled data) - privacy-violating upper bound
    add("Centralized (pooled data)", local_train(np.zeros(Xte_b.shape[1]), Xtr_b, ytr, 100, 0.1, 16, 1e-3, rng))
    # Federated
    w, _ = federated_train(clients, Xte_b, yte, seed=seed); add("FedAvg", w)
    for s in noise_levels:
        w, _ = federated_train(clients, Xte_b, yte, clip=clip, noise_mult=s, seed=seed)
        add(f"DP-FedAvg (noise={s})", w)
    return rows

all_rows = []
for seed in range(5):
    all_rows += run_experiment(seed)
res = pd.DataFrame(all_rows)
summary = (res.groupby("Model", sort=False)[["Test AUC", "Attack AUC"]]
              .agg(["mean", "std"]).round(3))
summary

